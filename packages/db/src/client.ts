import { mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { sql } from "drizzle-orm";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import { drizzle as drizzlePglite } from "drizzle-orm/pglite";
import { migrate as migratePglite } from "drizzle-orm/pglite/migrator";
import { drizzle as drizzlePostgres } from "drizzle-orm/postgres-js";
import { migrate as migratePostgres } from "drizzle-orm/postgres-js/migrator";
import postgres from "postgres";
import { z } from "zod";
import * as schema from "./schema";

/** One Drizzle database type, whichever client opened it. */
export type Database = PgDatabase<PgQueryResultHKT, typeof schema>;

export type DatabaseKind = "pglite" | "postgres";

export interface DatabaseHandle {
  readonly kind: DatabaseKind;
  readonly db: Database;
  /** Applies the migrations not yet applied, and returns how many it applied. */
  migrate(): Promise<number>;
  close(): Promise<void>;
}

export type DatabaseTarget =
  | { readonly kind: "pglite"; readonly dir: string }
  | { readonly kind: "postgres"; readonly url: string };

/** The one migrations folder, generated by `npm run db:generate` (ADR 0003). */
export const migrationsFolder = fileURLToPath(new URL("../drizzle", import.meta.url));

// Drizzle's migrator records each applied migration in this table, which it creates on its
// first run. The table's presence is checked first, because a query naming it fails without it.
const MIGRATIONS_TABLE_SQL =
  "SELECT to_regclass('drizzle.__drizzle_migrations') IS NOT NULL AS present";
const APPLIED_COUNT_SQL = "SELECT count(*)::int AS n FROM drizzle.__drizzle_migrations";

const countDifference = async (
  count: () => Promise<number>,
  apply: () => Promise<void>,
): Promise<number> => {
  const before = await count();
  await apply();
  return (await count()) - before;
};

const pgliteHandle = (client: PGlite): DatabaseHandle => {
  const db = drizzlePglite({ client, schema });
  const count = async () => {
    const table = await client.query<{ present: boolean }>(MIGRATIONS_TABLE_SQL);
    if (table.rows[0]?.present !== true) return 0;
    const result = await client.query<{ n: number }>(APPLIED_COUNT_SQL);
    return result.rows[0]?.n ?? 0;
  };
  return {
    kind: "pglite",
    db,
    migrate: () => countDifference(count, () => migratePglite(db, { migrationsFolder })),
    close: () => client.close(),
  };
};

/** A fresh in-memory PGlite with the migrations applied. For tests. */
export const createTestDatabase = async (): Promise<DatabaseHandle> => {
  const handle = pgliteHandle(new PGlite());
  await handle.migrate();
  return handle;
};

export type OpenOptions = {
  /** Runs the migrations on open (default true). `db:migrate` turns it off to count them. */
  readonly migrate?: boolean;
};

/** A PGlite database kept in a directory, created if missing. Opening it runs the migrations. */
export const openPgliteDirectory = async (
  dir: string,
  options: OpenOptions = {},
): Promise<DatabaseHandle> => {
  mkdirSync(dir, { recursive: true });
  const client = new PGlite(dir);
  const handle = pgliteHandle(client);
  try {
    await client.waitReady;
    if (options.migrate !== false) await handle.migrate();
  } catch (error) {
    await handle.close().catch(() => {});
    throw error;
  }
  return handle;
};

/**
 * A postgres.js database for a connection string. It connects on first use and is never
 * migrated on open: only `npm run db:migrate` migrates it.
 */
export const openPostgres = (url: string): DatabaseHandle => {
  const client = postgres(url, { onnotice: () => {} });
  const db = drizzlePostgres({ client, schema });
  const count = async () => {
    const table = await client.unsafe<{ present: boolean }[]>(MIGRATIONS_TABLE_SQL);
    if (table[0]?.present !== true) return 0;
    const rows = await client.unsafe<{ n: number }[]>(APPLIED_COUNT_SQL);
    return rows[0]?.n ?? 0;
  };
  return {
    kind: "postgres",
    db,
    migrate: () => countDifference(count, () => migratePostgres(db, { migrationsFolder })),
    close: () => client.end(),
  };
};

/** Opens whichever database a target names. A PGlite directory is migrated on open. */
export const openDatabase = async (
  target: DatabaseTarget,
  options: OpenOptions = {},
): Promise<DatabaseHandle> =>
  target.kind === "pglite" ? openPgliteDirectory(target.dir, options) : openPostgres(target.url);

const TableSchema = z.array(z.object({ present: z.boolean() })).length(1);

/**
 * Whether `audit_log` exists where the database's search path looks. It is also the CLIs'
 * first query, so a database that can't be reached fails here.
 */
export const hasAuditLogTable = async (db: Database): Promise<boolean> => {
  const rows = await db
    .select({ present: sql<boolean>`to_regclass('audit_log') IS NOT NULL` })
    .from(sql`(VALUES (1)) AS probe (n)`);
  const [row] = TableSchema.parse(rows);
  return row?.present === true;
};
